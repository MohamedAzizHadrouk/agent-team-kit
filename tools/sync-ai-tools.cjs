#!/usr/bin/env node
// Wakil – multi-tool sync.
// The single source of truth is .claude/ (agents, agent skills, commands) + CLAUDE.md, used as-is by Claude Code.
// This script GENERATES the files that Cursor and OpenAI Codex read, so the same agents, skills and commands
// work there too:
//   AGENTS.md                                   shared rules + how to run Wakil commands   (Codex, Cursor, others)
//   .agents/skills/wakil-<command>/SKILL.md     one skill per /wakil.* command  → Codex $wakil-x (and /skills) · Cursor /wakil-x
//   .cursor/commands/wakil.<command>.md         one Cursor command per /wakil.* command → Cursor /wakil.x (same as Claude Code)
//   .agents/skills/<agent>-<skill>/SKILL.md     the agents' method skills (Agent Skills standard)
//   .cursor/agents/<agent>.md                   Cursor subagents
//   .codex/agents/<agent>.toml                  Codex custom agents
//   .wakil/tools.json                           what was generated and when (read by Wakil Desktop)
// Never edit generated files: edit .claude/ or CLAUDE.md, then run   node tools/sync-ai-tools.cjs
// Only files listed in the previous .wakil/tools.json are ever deleted (stale generated files).
//
// --global  also installs the commands for YOUR user (~/.agents/skills/wakil-*/SKILL.md, read by Codex and Cursor in
//           every folder). Without it, the commands only exist when the tool is opened on the ecosystem root: Codex
//           stops at the nearest git root and Cursor reads only the opened folder, so a project's code folder
//           (often its own git repo) has no /wakil commands. The global skills only point to this ecosystem's files
//           (absolute path, written to your home folder – never to the repo). Once installed, every sync refreshes them.
'use strict'
const fs = require('fs')
const os = require('os')
const path = require('path')

const args = process.argv.slice(2)
const GLOBAL = args.includes('--global')
const ROOT = path.resolve(args.find((a) => !a.startsWith('--')) || path.join(__dirname, '..'))
const P = (...a) => path.join(ROOT, ...a)
const MARK = 'GENERATED by tools/sync-ai-tools.cjs'
const rel = (abs) => path.relative(ROOT, abs).split(path.sep).join('/')
const read = (p) => fs.readFileSync(p, 'utf8').replace(/^﻿/, '').replace(/\r\n/g, '\n')
const yamlStr = (s) => JSON.stringify(String(s ?? '').replace(/\s+/g, ' ').trim()) // JSON string = valid YAML

function frontmatter(src) {
  const m = src.match(/^---\n([\s\S]*?)\n---\n?/)
  const fm = {}
  if (!m) return { fm, body: src }
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([A-Za-z0-9_-]+)\s*:\s*(.*)$/)
    if (kv) fm[kv[1].toLowerCase()] = kv[2].trim().replace(/^["']|["']$/g, '')
  }
  return { fm, body: src.slice(m[0].length) }
}
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, e.name)
    if (e.isDirectory()) walk(abs, out)
    else out.push(abs)
  }
  return out
}

// ---------- read the sources ----------
if (!fs.existsSync(P('CLAUDE.md'))) {
  console.error(`No CLAUDE.md in ${ROOT} – run this from the ecosystem folder.`)
  process.exit(1)
}
const sources = []
const commands = fs.existsSync(P('.claude/commands'))
  ? fs.readdirSync(P('.claude/commands')).filter((f) => f.endsWith('.md')).sort().map((f) => {
      const file = P('.claude/commands', f)
      sources.push(file)
      const { fm, body } = frontmatter(read(file))
      const name = f.replace(/\.md$/, '')
      return { name, skill: slug(name), file: rel(file), description: fm.description || '', hint: fm['argument-hint'] || '', body }
    })
  : []
const agents = fs.existsSync(P('.claude/agents'))
  ? fs.readdirSync(P('.claude/agents'), { withFileTypes: true })
      .filter((d) => d.isDirectory() && !d.name.startsWith('_') && fs.existsSync(P('.claude/agents', d.name, `${d.name}.md`)))
      .map((d) => {
        const file = P('.claude/agents', d.name, `${d.name}.md`)
        sources.push(file)
        const { fm, body } = frontmatter(read(file))
        const skills = walk(P('.claude/agents', d.name, 'skills'))
          .filter((f) => path.basename(f) === 'SKILL.md')
          .sort()
          .map((f) => {
            sources.push(f)
            const s = frontmatter(read(f))
            const id = s.fm.skill || path.basename(path.dirname(f))
            return {
              agent: d.name,
              id,
              name: slug(`${d.name}-${id}`),
              category: s.fm.category || '',
              useWhen: s.fm['use-when'] || '',
              inputs: s.fm.inputs || '',
              output: s.fm.output || '',
              title: (s.body.match(/^#\s+(.+)$/m) || [])[1] || id,
              dir: path.dirname(f),
              file: rel(f),
              body: s.body,
            }
          })
        return { id: d.name, name: fm.name || d.name, description: fm.description || '', model: fm.model || 'inherit', file: rel(file), body, skills }
      })
  : []
sources.push(P('CLAUDE.md'))
const claudeMd = read(P('CLAUDE.md'))
const main = agents.find((a) => a.id === 'manager')
const specialists = agents.filter((a) => a.id !== 'manager')
const allSkills = agents.flatMap((a) => a.skills)

// ---------- writer that remembers what it generated ----------
const manifestPath = P('.wakil/tools.json')
let previous = { files: [] }
try {
  if (fs.existsSync(manifestPath)) previous = JSON.parse(read(manifestPath))
} catch {
  // e.g. merge conflict markers left in the file: regenerate it (stale files are then kept, never guessed)
  console.warn('Warning: .wakil/tools.json is not valid JSON – it is rewritten; stale generated files are not removed this time.')
}
const written = []
function write(relPath, content) {
  const abs = P(relPath)
  fs.mkdirSync(path.dirname(abs), { recursive: true })
  fs.writeFileSync(abs, content.replace(/\n{3,}/g, '\n\n'))
  written.push(relPath)
}
const header = (src) => `<!-- ${MARK} from ${src} – do not edit here: edit the source, then run \`node tools/sync-ai-tools.cjs\` -->`

// ---------- AGENTS.md ----------
const cmdRows = commands
  .map((c) => `| \`/${c.name}\` | \`/${c.name}\` or \`/${c.skill}\` | \`$${c.skill}\` | ${c.description.replace(/\|/g, '\\|')} |`)
  .join('\n')
const agentRows = agents
  .map((a) => `| ${a.id} | \`${a.file}\` | ${a.id === 'manager' ? 'main agent (you)' : `\`.cursor/agents/${a.id}.md\` · \`.codex/agents/${a.id}.toml\``} | ${a.skills.length} |`)
  .join('\n')
const skillRows = allSkills.map((s) => `| ${s.agent} | ${s.category} | \`${s.name}\` | ${s.useWhen.replace(/\|/g, '/')} |`).join('\n')
write(
  'AGENTS.md',
  `${header('CLAUDE.md + .claude/')}
# Wakil ecosystem – instructions for every AI coding agent (Claude Code, Cursor, Codex…)

This folder is a **Wakil ecosystem**. It works the same way in Claude Code, Cursor and OpenAI Codex:
the agents, their skills and the \`/wakil.*\` commands all live in \`.claude/\` (single source of truth) and are
mirrored for the other tools by \`tools/sync-ai-tools.cjs\`. Wakil Desktop shows the result.

## Who you are
Unless the user picked another agent, **you are the manager**: before acting on any Wakil command or client task,
read \`${main ? main.file : '.claude/agents/manager/manager.md'}\` and follow it. It orchestrates the specialists listed below.

## Running a Wakil command
The user may type a command in any of these forms – they all mean the same thing:

| Claude Code | Cursor | Codex | What it does |
|---|---|---|---|
${cmdRows}

How to run one (any tool): open \`.claude/commands/<name>.md\` (e.g. \`/wakil.news\` → \`.claude/commands/wakil.news.md\`),
treat the text the user wrote after the command as **the arguments** (\`$ARGUMENTS\` in the file), and follow its
**Steps** and **Rules** exactly. The same instructions are also available as Cursor commands
(\`.cursor/commands/wakil.*.md\`) and as skills for Codex and Cursor (\`.agents/skills/wakil-*/SKILL.md\`).
In Codex, commands are skills: type \`$wakil-x\` (or pick it in \`/skills\`). If the user writes \`/wakil.x\` or
\`wakil.x\` as plain text in any tool, treat it as that command: run the skill \`wakil-x\` / follow \`.claude/commands/wakil.x.md\`.

## Agents (specialists)
| Agent | Definition (source) | Cursor / Codex | Skills |
|---|---|---|---|
${agentRows}

Delegate a task to a specialist with your tool's subagent feature – Claude Code: the Agent tool with
\`subagent_type: <agent>\`; Cursor: \`/<agent> <task>\` or "use the <agent> subagent"; Codex: ask to spawn the custom
agent \`<agent>\`. If your tool cannot run subagents, do the work yourself **as that agent**: read its definition file
and its \`skills/INDEX.md\`, and follow them. Every specialist brief starts with
\`TASK: <entity>/<project|none>/<task-id>\`.

## Skills (methods of the specialists)
Each agent's skills are indexed in \`.claude/agents/<agent>/skills/INDEX.md\`. They are mirrored as Agent Skills in
\`.agents/skills/<agent>-<skill>/\` for Cursor and Codex.

| Agent | Category | Skill | Use when |
|---|---|---|---|
${skillRows}

## Tool notes
- Connectors (Trello, Gmail/Outlook, Figma, GitHub…) are configured per tool. If the one a command needs is missing in
  your tool, say so and stop (\`NEEDS_INFO\`) – never work around it. \`tools/outlook-draft.ps1\` works from any tool.
- Changed an agent, a skill or a command in \`.claude/\`? Run \`node tools/sync-ai-tools.cjs\` (or \`/wakil.sync-tools\`).
- Commands missing because the tool is open on a sub-folder (a project's code repo)? Run
  \`node tools/sync-ai-tools.cjs --global\` once: the commands are then installed for the user and work in any folder.
- Never edit the generated files (\`AGENTS.md\`, \`.agents/skills/\`, \`.cursor/commands/\`, \`.cursor/agents/\`, \`.codex/agents/\`).

---

# Shared rules (from CLAUDE.md – read by every agent)

${claudeMd.replace(/^#\s+.+\n/, '')}
`,
)

// ---------- one skill per command ----------
for (const c of commands) {
  const body = c.body
    .replace(/Arguments:\s*`\$ARGUMENTS`/g, 'Arguments: the text the user wrote after the command')
    .replace(/\$ARGUMENTS/g, 'the arguments the user gave')
  write(
    `.agents/skills/${c.skill}/SKILL.md`,
    `---
name: ${c.skill}
description: ${yamlStr(`Wakil command /${c.name} – ${c.description}. Use only when the user runs /${c.name}, /${c.skill} or $${c.skill}.`)}
disable-model-invocation: true
metadata:
  source: ${yamlStr(c.file)}
  argument-hint: ${yamlStr(c.hint)}
---
${header(c.file)}

> Wakil command **/${c.name}** – Claude Code \`/${c.name}\` · Cursor \`/${c.skill}\` · Codex \`$${c.skill}\`.
> Arguments: everything the user wrote after the command${c.hint ? ` – expected: \`${c.hint}\`` : ''}.
> Read \`AGENTS.md\` (shared rules) first if you have not yet.

${body}`,
  )
  // No agents/openai.yaml with `allow_implicit_invocation: false` any more: Codex then left the command out of its
  // skill list, so `$wakil-x` and plain "/wakil.x" requests were not found. The description already limits its use.

  // Cursor custom command: typed exactly like in Claude Code (/wakil.focus …); the text after it is the arguments.
  write(
    `.cursor/commands/${c.name}.md`,
    `${header(c.file)}

> Wakil command **/${c.name}**. Arguments: everything the user wrote after \`/${c.name}\`${c.hint ? ` – expected: \`${c.hint}\`` : ''}
> (none = use the defaults described below). Read \`AGENTS.md\` (shared rules) first if you have not yet.

${body}`,
  )
}

// ---------- agents' method skills ----------
for (const s of allSkills) {
  const desc = `${s.agent} skill (${s.category}) – ${s.title}. Use when: ${s.useWhen}.${s.output ? ` Output: ${s.output}.` : ''}`
  write(
    `.agents/skills/${s.name}/SKILL.md`,
    `---
name: ${s.name}
description: ${yamlStr(desc)}
metadata:
  source: ${yamlStr(s.file)}
  agent: ${yamlStr(s.agent)}
  category: ${yamlStr(s.category)}
---
${header(s.file)}

${s.body}`,
  )
  // extra files next to the skill (scripts/, references/…)
  for (const extra of walk(s.dir).filter((f) => path.basename(f) !== 'SKILL.md')) {
    const target = `.agents/skills/${s.name}/${path.relative(s.dir, extra).split(path.sep).join('/')}`
    fs.mkdirSync(path.dirname(P(target)), { recursive: true })
    fs.copyFileSync(extra, P(target))
    written.push(target)
  }
}

// ---------- subagents ----------
const agentFooter = (a) => `

---
Your skills: read \`.claude/agents/${a.id}/skills/INDEX.md\` first, pick the rows that match the brief, follow those
\`SKILL.md\` files (also available as \`.agents/skills/${a.id}-*\`). Shared rules: \`AGENTS.md\` / \`CLAUDE.md\`.`
for (const a of specialists) {
  write(
    `.cursor/agents/${a.id}.md`,
    `---
name: ${a.id}
description: ${yamlStr(a.description)}
model: inherit
---
${header(a.file)}
${a.body}${agentFooter(a)}
`,
  )
  write(
    `.codex/agents/${a.id}.toml`,
    `# ${MARK} from ${a.file} – do not edit here.
name = ${JSON.stringify(a.id)}
description = ${JSON.stringify(a.description.replace(/\s+/g, ' ').trim())}
developer_instructions = ${JSON.stringify(a.body.trim() + agentFooter(a))}
`,
  )
}

// ---------- remove stale generated files ----------
let removed = 0
for (const f of previous.files || []) {
  if (written.includes(f)) continue
  const abs = P(f)
  if (!fs.existsSync(abs)) continue
  fs.rmSync(abs)
  removed++
  // drop now-empty folders up to the generated root
  let dir = path.dirname(abs)
  while (dir.startsWith(P('.agents')) || dir.startsWith(P('.cursor')) || dir.startsWith(P('.codex'))) {
    if (fs.readdirSync(dir).length) break
    fs.rmdirSync(dir)
    dir = path.dirname(dir)
  }
}

// ---------- user-level (global) command skills ----------
// Thin pointers to the ecosystem's own command files, so the commands work in any folder opened in Codex or Cursor.
const userSkills = path.join(os.homedir(), '.agents', 'skills')
const globalMarker = path.join(userSkills, '.wakil-global.json')
const rootSlash = ROOT.split(path.sep).join('/')
let globalInstalled = false
try {
  globalInstalled = JSON.parse(read(globalMarker)).root === rootSlash
} catch {}
let globalCount = 0
if (GLOBAL || globalInstalled) {
  fs.mkdirSync(userSkills, { recursive: true })
  const names = new Set(commands.map((c) => c.skill))
  for (const c of commands) {
    const dir = path.join(userSkills, c.skill)
    fs.mkdirSync(dir, { recursive: true })
    fs.writeFileSync(
      path.join(dir, 'SKILL.md'),
      `---
name: ${c.skill}
description: ${yamlStr(`Wakil command /${c.name} – ${c.description}. Use only when the user runs /${c.name}, /${c.skill} or $${c.skill}.`)}
disable-model-invocation: true
metadata:
  source: ${yamlStr(`${rootSlash}/${c.file}`)}
  argument-hint: ${yamlStr(c.hint)}
---
<!-- ${MARK} (--global) for the Wakil ecosystem at ${rootSlash} – do not edit here. -->

# Wakil command /${c.name}

The Wakil ecosystem lives in **\`${rootSlash}\`** (the ecosystem root), which may not be the folder open in this tool.

1. Read \`${rootSlash}/AGENTS.md\` (shared rules) if you have not yet in this conversation.
2. Read \`${rootSlash}/${c.file}\` and follow its **Steps** and **Rules** exactly. The text the user wrote after the
   command is the arguments (\`$ARGUMENTS\` in that file)${c.hint ? ` – expected: \`${c.hint}\`` : ''}.
3. Every relative path in those files (\`.claude/…\`, \`entities/…\`, \`ecosystem/…\`, \`tools/…\`) is relative to
   \`${rootSlash}\` – never to the current folder. Run their scripts from that root.
`,
    )
    globalCount++
  }
  // remove global Wakil skills of commands that no longer exist (only ones this script generated for this root)
  for (const e of fs.readdirSync(userSkills, { withFileTypes: true })) {
    if (!e.isDirectory() || !e.name.startsWith('wakil-') || names.has(e.name)) continue
    const file = path.join(userSkills, e.name, 'SKILL.md')
    if (fs.existsSync(file) && read(file).includes(`${MARK} (--global) for the Wakil ecosystem at ${rootSlash}`)) {
      fs.rmSync(path.join(userSkills, e.name), { recursive: true })
    }
  }
  fs.writeFileSync(globalMarker, JSON.stringify({ root: rootSlash, generatedAt: new Date().toISOString(), commands: [...names] }, null, 2) + '\n')
}

// ---------- manifest ----------
const sourceMtime = Math.max(...sources.map((f) => fs.statSync(f).mtimeMs))
fs.mkdirSync(P('.wakil'), { recursive: true })
fs.writeFileSync(
  manifestPath,
  JSON.stringify(
    {
      generator: 'tools/sync-ai-tools.cjs',
      generatedAt: new Date().toISOString(),
      sourceMtime: new Date(sourceMtime).toISOString(),
      tools: {
        claude: { reads: ['CLAUDE.md', '.claude/agents', '.claude/commands'] },
        cursor: { reads: ['AGENTS.md', '.cursor/commands', '.agents/skills', '.cursor/agents'] },
        codex: { reads: ['AGENTS.md', '.agents/skills', '.codex/agents'] },
      },
      counts: { commands: commands.length, agents: agents.length, subagents: specialists.length, skills: allSkills.length },
      files: written.sort(),
    },
    null,
    2,
  ) + '\n',
)
console.log(
  `Wakil sync: ${commands.length} commands, ${specialists.length} subagents, ${allSkills.length} skills → ` +
    `AGENTS.md, .agents/skills (${commands.length + allSkills.length}), .cursor/commands (${commands.length}), .cursor/agents, .codex/agents` +
    (removed ? ` · ${removed} stale file(s) removed` : '') +
    (globalCount
      ? ` · ${globalCount} global command skills → ${userSkills}`
      : '\nTip: run with --global so the /wakil commands also work when Cursor or Codex is opened on a sub-folder.'),
)
